let num1=45;
let num2=30;
let operator="*";
switch(operator)
{
    case '+':
        console.log(num1+num2);
        break; 
    case '-':
        console.log(num1-num2);
        break;
    case '*':
        console.log(num1*num2);
        break;
    case '/':
        console.log(num1/num2);
        break;
    default:
        console.log("Invalid operator");

}